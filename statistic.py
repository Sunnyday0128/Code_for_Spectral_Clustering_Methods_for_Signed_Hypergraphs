# 转换为ANOVA要求的长格式（long format）
long_df = pd.melt(
    df, 
    id_vars=["Graph_ID"],  # 保留生成图编号作为重复测量的标识
    var_name="Kernel",     # 新列：Kernel类型（Kernel1~Kernel4）
    value_name="Score"     # 新列：划分结果（你的实验指标）
)

# ---------------------- 3. 重复测量ANOVA分析 ----------------------
# 模型：Score ~ Kernel（组内因素） + (1|Graph_ID)（控制生成图的随机效应）
anova_model = AnovaRM(
    data=long_df, 
    depvar="Score",    # 因变量：划分结果
    subject="Graph_ID",# 受试者：生成图（每个图被重复测量4次）
    within=["Kernel"]  # 组内因素：Kernel类型
)
anova_results = anova_model.fit()

# ---------------------- 4. 结果输出与解读 ----------------------
print("=== 重复测量ANOVA结果 ===")
print(anova_results)
print("\n=== 核心结论 ===")
p_value = anova_results.anova_table["Pr > F"].iloc[0]
if p_value < 0.05:
    print(f"✅ Kernel类型主效应显著（p={p_value:.4f} < 0.05）：方法间存在本质差异，非随机性导致。")
else:
    print(f"❌ Kernel类型主效应不显著（p={p_value:.4f} ≥ 0.05）：方法间差异可能由随机性导致。")

# ---------------------- 5. 事后检验（若ANOVA显著） ----------------------
if p_value < 0.05:
    print("\n=== 事后检验（Tukey HSD）：具体哪两种Kernel有差异 ===")
    tukey_result = pairwise_tukeyhsd(
        endog=long_df["Score"], 
        groups=long_df["Kernel"], 
        alpha=0.05
    )
    print(tukey_result)
